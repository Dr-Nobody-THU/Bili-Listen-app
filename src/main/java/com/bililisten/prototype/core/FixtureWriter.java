package com.bililisten.prototype.core;

import com.bililisten.prototype.model.QueueItem;
import com.bililisten.prototype.model.ResolvedQueue;

import java.io.IOException;
import java.io.Writer;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Properties;

public final class FixtureWriter {
    public void write(ResolvedQueue queue, Path outputFile) {
        Properties properties = new Properties();

        if (queue.collectionId() != null) {
            properties.setProperty("collection.id", queue.collectionId());
            properties.setProperty("collection.title", queue.collectionTitle());
        }

        for (int index = 0; index < queue.items().size(); index++) {
            QueueItem item = queue.items().get(index);
            String prefix = "item." + index + ".";
            properties.setProperty(prefix + "bvid", item.key().bvid());
            properties.setProperty(prefix + "cid", Long.toString(item.key().cid()));
            properties.setProperty(prefix + "page", Integer.toString(item.pageNumber()));
            properties.setProperty(prefix + "title", item.title());
            properties.setProperty(prefix + "durationMs", Long.toString(item.durationMs()));
            if (item.coverUrl() != null && !item.coverUrl().isBlank()) {
                properties.setProperty(prefix + "coverUrl", item.coverUrl());
            }
        }

        try {
            Path parent = outputFile.getParent();
            if (parent != null) {
                Files.createDirectories(parent);
            }
            try (Writer writer = Files.newBufferedWriter(outputFile, StandardCharsets.UTF_8)) {
                properties.store(writer, "Generated by Bili Listen Prototype");
            }
        } catch (IOException exception) {
            throw new IllegalStateException("Failed to write fixture file: " + outputFile, exception);
        }
    }
}
